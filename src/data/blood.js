// Helper to compute a simple "deviation score" for layout/display
export function computeBloodScore(marker) {
  if (!marker) return 50;
  const ageImp = Math.abs(marker.age_impact || 0);
  return Math.max(20, Math.min(95, 70 - ageImp * 8));
}
